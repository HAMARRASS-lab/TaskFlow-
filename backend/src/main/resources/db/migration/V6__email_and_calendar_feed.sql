-- Email verification, daily digest opt-out and the private calendar (iCalendar) subscription feed.
ALTER TABLE users ADD COLUMN email_verified BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE users ADD COLUMN digest_enabled BOOLEAN DEFAULT TRUE NOT NULL;
ALTER TABLE users ADD COLUMN calendar_feed_token VARCHAR(64);

-- Accounts created before verification existed are trusted as-is.
UPDATE users SET email_verified = TRUE;

CREATE UNIQUE INDEX ux_users_calendar_feed_token ON users (calendar_feed_token);

-- Single-use links sent by email (verification, password reset). Only a SHA-256 hash of the token is stored.
CREATE TABLE user_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    purpose     VARCHAR(20)  NOT NULL,
    token_hash  VARCHAR(64)  NOT NULL UNIQUE,
    expires_at  TIMESTAMP    NOT NULL,
    used_at     TIMESTAMP,
    created_at  TIMESTAMP    NOT NULL
);

CREATE INDEX idx_user_tokens_user_purpose ON user_tokens (user_id, purpose);
