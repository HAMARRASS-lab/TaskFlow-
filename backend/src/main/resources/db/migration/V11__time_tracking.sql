-- Time tracking: an optional estimate per task, and the time logged on it, by timer or by hand.
ALTER TABLE tasks ADD COLUMN estimate_minutes INTEGER;

-- A running timer has no ended_at and no seconds yet; each user runs at most one (enforced by the service).
CREATE TABLE time_entries (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id     BIGINT        NOT NULL REFERENCES tasks (id) ON DELETE CASCADE,
    user_id     BIGINT        REFERENCES users (id) ON DELETE SET NULL,
    started_at  TIMESTAMP     NOT NULL,
    ended_at    TIMESTAMP,
    seconds     BIGINT,
    note        VARCHAR(200)
);

CREATE INDEX idx_time_entries_task ON time_entries (task_id, started_at);
CREATE INDEX idx_time_entries_user_running ON time_entries (user_id, ended_at);
