-- In-app notifications (the bell): a task assigned to you, a comment on a task you follow, a meeting invitation.
-- They go away with their recipient, task or meeting; the actor is kept as "someone" if their account is deleted.
CREATE TABLE notifications (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id  BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    actor_id      BIGINT        REFERENCES users (id) ON DELETE SET NULL,
    type          VARCHAR(30)   NOT NULL,
    task_id       BIGINT        REFERENCES tasks (id) ON DELETE CASCADE,
    meeting_id    BIGINT        REFERENCES meetings (id) ON DELETE CASCADE,
    subject       VARCHAR(200)  NOT NULL,
    read_at       TIMESTAMP,
    created_at    TIMESTAMP     NOT NULL
);

CREATE INDEX idx_notifications_recipient_created ON notifications (recipient_id, created_at);
