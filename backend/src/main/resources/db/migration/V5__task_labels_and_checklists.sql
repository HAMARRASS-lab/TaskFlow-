-- Free-form labels (tags) on a task, stored lower-cased; they go away with their task.
CREATE TABLE task_labels (
    task_id  BIGINT       NOT NULL REFERENCES tasks (id) ON DELETE CASCADE,
    name     VARCHAR(30)  NOT NULL,
    PRIMARY KEY (task_id, name)
);

-- Checklist (subtasks) of a task, in display order.
CREATE TABLE task_checklist_items (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id     BIGINT        NOT NULL REFERENCES tasks (id) ON DELETE CASCADE,
    title       VARCHAR(200)  NOT NULL,
    done        BOOLEAN       NOT NULL DEFAULT FALSE,
    sort_order  INT           NOT NULL
);

CREATE INDEX idx_task_checklist_items_task ON task_checklist_items (task_id, sort_order);
