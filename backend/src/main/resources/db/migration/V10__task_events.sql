-- Activity history of a task: who changed its status, priority, assignee or due date, and when.
-- Values are stored as text (the assignee by name) so the history reads the same after a user is deleted;
-- the actor is then shown as a former user.
CREATE TABLE task_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id     BIGINT        NOT NULL REFERENCES tasks (id) ON DELETE CASCADE,
    actor_id    BIGINT        REFERENCES users (id) ON DELETE SET NULL,
    type        VARCHAR(20)   NOT NULL,
    old_value   VARCHAR(200),
    new_value   VARCHAR(200),
    created_at  TIMESTAMP     NOT NULL
);

CREATE INDEX idx_task_events_task_created ON task_events (task_id, created_at);
